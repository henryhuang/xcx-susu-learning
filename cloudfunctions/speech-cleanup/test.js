const assert=require('node:assert/strict');
const {cleanup}=require('./cleanup');
const copy=value=>value&&JSON.parse(JSON.stringify(value));
(async()=>{
 let time=1000000;
 const data={speech_recordings:{},speech_summaries:{}};
 const writes=[];
 const doc=(name,id)=>({get:async()=>({data:copy(data[name][id])}),update:async({data:patch})=>{Object.assign(data[name][id],patch);writes.push(id);}});
 const collection=name=>({doc:id=>doc(name,id),where:()=>({limit:()=>({get:async()=>({data:Object.entries(data[name]).filter(([,r])=>r.expiresAt>0&&r.expiresAt<=time).map(([id,r])=>({_id:id,...copy(r)}))})})})});
 const db={collection,runTransaction:fn=>fn({collection}),command:{gt:()=>({and:()=>({})}),lte:()=>({})}};
 const add=(id,state)=>data.speech_recordings[id]={learnerId:'susu',summaryId:'summary',state,path:`speech/susu/summary/${id}.mp3`,fileID:`cloud://private/speech/susu/summary/${id}.mp3`,expiresAt:1};
 add('active','active');add('obsolete','obsolete');add('staging','staging');add('pointed','obsolete');add('retry','deleting');add('foreign','obsolete');
 data.speech_recordings.foreign.path='other/voice.mp3';
 data.speech_summaries.summary={recording:{attemptId:'pointed',fileID:data.speech_recordings.pointed.fileID}};
 const deleted=[];let fail=true;
 const storage={delete:async id=>{if(id.endsWith('/retry.mp3')&&fail)throw Error('temporary');deleted.push(id);}};
 assert.equal((await cleanup({db,storage,now:()=>time})).deleted,2);
 assert.equal(data.speech_recordings.pointed.state,'active','Active summary pointer must be repaired and preserved');
 assert.equal(data.speech_recordings.active.state,'active');
 assert.equal(data.speech_recordings.foreign.state,'obsolete');
 assert.equal(data.speech_recordings.retry.state,'deleting');
 fail=false;time+=600001;
 assert.equal((await cleanup({db,storage,now:()=>time})).deleted,1);
 assert.equal(deleted.length,3);
 add('dad-temp','obsolete');data.speech_recordings['dad-temp'].learnerId='dad';
 data.speech_recordings['dad-temp'].path='speech/dad/summary/dad-temp.mp3';
 data.speech_recordings['dad-temp'].fileID='cloud://private/speech/dad/summary/dad-temp.mp3';
 assert.equal((await cleanup({db,storage,now:()=>time})).deleted,1);
 assert(deleted.includes('cloud://private/speech/dad/summary/dad-temp.mp3'));
 assert(!writes.includes('active'));assert(!deleted.some(id=>id.includes('/pointed.mp3')));
 console.log('Passed: cleanup preserves active recordings, repairs pointers, retries deletion and restricts paths.');
})().catch(error=>{console.error(error);process.exitCode=1;});
